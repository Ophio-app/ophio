// Regenerates src/protocol/types.ts from the ts-rs output in
// src/protocol/generated (written by `cargo test -p protocol`).
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "protocol");
const names = readdirSync(join(root, "generated"))
  .filter((f) => f.endsWith(".ts"))
  .map((f) => f.slice(0, -3))
  .sort();
const body = names.map((n) => `export type { ${n} } from "./generated/${n}";`).join("\n");
writeFileSync(
  join(root, "types.ts"),
  `// SPDX-License-Identifier: Apache-2.0\n// Generated by scripts/protocol-barrel.mjs. Do not edit.\n\n${body}\n`,
);
console.log(`protocol barrel: ${names.length} types`);
