/** Missing policy is a refusal, not permission to send a future request. */
export function requestRefusal(policy: RequestPolicy | undefined, features: readonly string[] = []): string | null {
  if (!policy) return "This request has no compatibility policy. Nothing was sent.";
  if ("allow" in policy) return null;
  return features.includes(policy.feature) ? null : "This computer needs an update to handle this request. Nothing was sent.";
}
