// Tauri config owns the application id and label. Android copies are generated.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const config = JSON.parse(fs.readFileSync(path.join(root, 'tauri.conf.json'), 'utf8'));
if(!/^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)+$/.test(config.identifier))throw new Error('Invalid Android application id.');
// Tauri's project templates carry neither checksum; a regenerated project must keep both.
const gradleFile = name => { const file = path.join(root,'gen/android/gradle',name); return fs.existsSync(file) ? fs.readFileSync(file,'utf8') : ''; };
if(!/^distributionSha256Sum=[0-9a-f]{64}$/m.test(gradleFile('wrapper/gradle-wrapper.properties'))||!gradleFile('verification-metadata.xml').includes('<verify-metadata>true</verify-metadata>'))throw new Error('Android Gradle checksums missing: keep distributionSha256Sum and gradle/verification-metadata.xml.');
const gradle = path.join(root,'gen/android/app/build.gradle.kts');
const oldId = fs.readFileSync(gradle,'utf8').match(/namespace = "([^"]+)"/)[1];
fs.writeFileSync(gradle, fs.readFileSync(gradle,'utf8').replaceAll(`"${oldId}"`, `"${config.identifier}"`));
const java = folder => path.join(root,folder,'src/main/java');
// Remove directories an application-id move leaves empty, up to the source root.
const prune = (start, stop) => { for (let dir = start; dir !== stop && fs.readdirSync(dir).length === 0; dir = path.dirname(dir)) fs.rmdirSync(dir); };
const oldSource = path.join(java('gen/android/app'),...oldId.split('.'),'MainActivity.kt');
const newSource = path.join(java('gen/android/app'),...config.identifier.split('.'),'MainActivity.kt');
const source=fs.readFileSync(oldSource,'utf8').replace(`package ${oldId}`,`package ${config.identifier}`);
fs.mkdirSync(path.dirname(newSource),{recursive:true});if(oldSource!==newSource){fs.unlinkSync(oldSource);prune(path.dirname(oldSource),java('gen/android/app'));}fs.writeFileSync(newSource,source);
// The Gradle build helpers live under the same package path.
const oldTasks = path.join(java('gen/android/buildSrc'),...oldId.split('.'),'kotlin');
const newTasks = path.join(java('gen/android/buildSrc'),...config.identifier.split('.'),'kotlin');
if(oldTasks!==newTasks&&fs.existsSync(oldTasks)){fs.mkdirSync(path.dirname(newTasks),{recursive:true});fs.renameSync(oldTasks,newTasks);prune(path.dirname(oldTasks),java('gen/android/buildSrc'));}
const xml = value => value.replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&apos;'}[c]));
const label=xml(config.productName);
fs.writeFileSync(path.join(root,'gen/android/app/src/main/res/values/strings.xml'),`<!-- Generated by tools/sync-native.mjs. SPDX-License-Identifier: Apache-2.0 -->\n<resources><string name="app_name">${label}</string><string name="main_activity_title">${label}</string></resources>\n`);
const tokens=fs.readFileSync(path.join(root,'../src/design/tokens.css'),'utf8').split(':root[data-theme="dark"]');
for (const [i,folder] of ['values','values-night'].entries()) {
  const accent=tokens[i].match(/--accent:\s*(#[a-fA-F0-9]{6})/)[1];
  const backgrounds=i===0 ? tokens.map((text,index)=>`<color name="app_background_${index===0?'light':'dark'}">${text.match(/--bg:\s*(#[a-fA-F0-9]{6})/)[1]}</color>`).join('') : '';
  fs.writeFileSync(path.join(root,`gen/android/app/src/main/res/${folder}/colors.xml`),`<!-- Generated from design tokens. SPDX-License-Identifier: Apache-2.0 -->\n<resources><color name="app_accent">${accent}</color>${backgrounds}</resources>\n`);
}
const brand=fs.readFileSync(path.join(root,'../src/brand.ts'),'utf8');
const scheme=brand.match(/PAIRING_SCHEME = "([^"]+)"/)[1];
const hostConfig=fs.readFileSync(path.join(root,'../../crates/companion/src/config.rs'),'utf8');
const ports = fs.readFileSync(
  path.join(root, "../../crates/ports/src/lib.rs"),
  "utf8",
);
const hostName =
  hostConfig.includes("APP_NAME: &str = ports::PROGRAM_NAME;") &&
  hostConfig.includes("PAIR_SCHEME: &str = APP_NAME;")
    ? ports.match(/PROGRAM_NAME: &str = "([^"]+)"/)?.[1]
    : undefined;
if (hostName !== scheme)
  throw new Error("Phone pairing scheme does not match the computer's PAIR_SCHEME.");
