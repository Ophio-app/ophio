//! Voice control observations and receipts. Audio and field values are absent.
use crate::{capability::Availability, control::LeaseView, ids::TargetId, time::Timestamp};
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;

#[derive(
    Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, schemars::JsonSchema, ts_rs::TS,
)]
#[serde(rename_all = "snake_case")]
#[ts(export)]
pub enum VoiceTarget {
    Browser,
    Desktop,
}
#[derive(
    Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, schemars::JsonSchema, ts_rs::TS,
)]
#[serde(rename_all = "snake_case")]
#[ts(export)]
pub enum VoiceActionKind {
    Click,
    Type,
    Scroll,
    Navigate,
    Back,
    Forward,
    SwitchTab,
    Focus,
    PressKey,
    Cancel,
    None,
}
#[derive(
    Debug, Clone, Copy, PartialEq, Serialize, Deserialize, schemars::JsonSchema, ts_rs::TS,
)]
#[ts(export)]
pub struct VoiceBounds {
    pub x: f64,
    pub y: f64,
    pub width: f64,
    pub height: f64,
}
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, schemars::JsonSchema, ts_rs::TS)]
#[ts(export)]
pub struct VoiceElement {
    pub id: String,
    pub role: String,
    pub name: String,
    pub bounds: VoiceBounds,
    pub visible: bool,
    pub enabled: bool,
    pub focused: bool,
    pub sensitive: bool,
    pub destructive: bool,
}
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, schemars::JsonSchema, ts_rs::TS)]
#[ts(export)]
pub struct VoiceChoice {
    pub choice: String,
    pub confidence: f64,
    pub probabilities: BTreeMap<String, f64>,
}
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, schemars::JsonSchema, ts_rs::TS)]
#[ts(export)]
pub struct VoiceScore {
    pub score: f64,
    pub confidence: f64,
    pub probabilities: BTreeMap<String, f64>,
}
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, schemars::JsonSchema, ts_rs::TS)]
#[ts(export)]
pub struct VoiceAnswers {
    pub intent: VoiceChoice,
    pub target: VoiceChoice,
    pub complete: VoiceScore,
    pub is_command: VoiceScore,
    pub destructive: VoiceScore,
    pub is_correction: VoiceScore,
}
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, schemars::JsonSchema, ts_rs::TS)]
#[ts(export)]
pub struct VoiceAction {
    pub kind: VoiceActionKind,
    pub target: Option<VoiceElement>,
    /// Literal transcript span, never generated by an assessor.
    pub literal: Option<String>,
    pub scroll_y: i32,
    pub previous_tab: bool,
}
#[derive(
    Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, schemars::JsonSchema, ts_rs::TS,
)]
#[serde(rename_all = "snake_case")]
#[ts(export)]
pub enum VoicePhase {
    Ready,
    Assessing,
    Waiting,
    Disambiguation,
    Confirm,
    Refused,
    Acting,
    Stopped,
    OutcomeUnknown,
}
#[derive(
    Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, schemars::JsonSchema, ts_rs::TS,
)]
#[serde(rename_all = "snake_case")]
#[ts(export)]
pub enum VoiceStopCause {
    Stop,
    LocalStop,
    ScreenLock,
    Revoked,
    Heartbeat,
    Idle,
    StepLimit,
    Stall,
    Shutdown,
    Restart,
    CapabilityLost,
}
#[derive(
    Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, schemars::JsonSchema, ts_rs::TS,
)]
#[serde(rename_all = "snake_case")]
#[ts(export)]
pub enum VoiceOutcome {
    Assessed,
    Ignored,
    Refused,
    Cancelled,
    Superseded,
    DryRun,
    Applied,
    StaleTarget,
    Failed,
    Unknown,
}
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, schemars::JsonSchema, ts_rs::TS)]
#[ts(export)]
pub struct VoiceStep {
    pub utterance_id: String,
    pub transcript: String,
    pub at: Timestamp,
    pub answers: Option<VoiceAnswers>,
    pub action: Option<VoiceAction>,
    pub outcome: VoiceOutcome,
    pub detail: String,
    pub jev_usage: Option<JevUsage>,
}
/// What Jev reported using to answer one command.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, schemars::JsonSchema, ts_rs::TS)]
#[ts(export)]
pub struct JevUsage {
    #[schemars(range(max = crate::MAX_SAFE_INTEGER))]
    pub input_tokens: Option<u64>,
    #[schemars(range(max = crate::MAX_SAFE_INTEGER))]
    pub output_tokens: Option<u64>,
}
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, schemars::JsonSchema, ts_rs::TS)]
#[ts(export)]
pub struct VoicePicture {
    /// A bounded still image for this phone only; never sent for assessment.
    pub png_base64: String,
    pub at: Timestamp,
}
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, schemars::JsonSchema, ts_rs::TS)]
#[ts(export)]
pub struct VoiceSessionView {
    pub session_id: String,
    pub target: VoiceTarget,
    pub target_id: TargetId,
    pub lease: LeaseView,
    pub dry_run: bool,
    pub phase: VoicePhase,
    pub transcript: String,
    pub understood: String,
    #[schemars(range(max = crate::MAX_SAFE_INTEGER))]
    pub prompt_id: u64,
    pub choices: Vec<VoiceElement>,
    pub picture: Option<VoicePicture>,
    pub steps: Vec<VoiceStep>,
    pub ended: Option<VoiceStopCause>,
}
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, schemars::JsonSchema, ts_rs::TS)]
#[ts(export)]
pub struct VoiceSettings {
    #[schemars(range(max = crate::MAX_SAFE_INTEGER))]
    pub revision: u64,
    pub browser: bool,
    pub desktop: bool,
}
impl Default for VoiceSettings {
    fn default() -> Self {
        Self {
            revision: 0,
            browser: true,
            desktop: true,
        }
    }
}
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, schemars::JsonSchema, ts_rs::TS)]
#[ts(export)]
pub struct VoiceView {
    pub settings: VoiceSettings,
    pub voice_browser: Availability,
    pub voice_desktop: Availability,
    pub speech: Availability,
    pub session: Option<VoiceSessionView>,
}
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, schemars::JsonSchema, ts_rs::TS)]
#[serde(tag = "operation", rename_all = "snake_case")]
#[ts(export)]
pub enum VoiceOperation {
    Start {
        target: VoiceTarget,
        target_id: TargetId,
        #[schemars(range(max = crate::MAX_SAFE_INTEGER))]
        geometry_revision: u64,
        dry_run: bool,
        disclosure_accepted: bool,
    },
    Transcript {
        session_id: String,
        utterance_id: String,
        #[schemars(range(max = crate::MAX_SAFE_INTEGER))]
        revision: u64,
        text: String,
        final_segment: bool,
    },
    Choose {
        session_id: String,
        #[schemars(range(max = crate::MAX_SAFE_INTEGER))]
        prompt_id: u64,
        element_id: String,
    },
    Confirm {
        session_id: String,
        #[schemars(range(max = crate::MAX_SAFE_INTEGER))]
        prompt_id: u64,
    },
    Cancel {
        session_id: String,
        #[schemars(range(max = crate::MAX_SAFE_INTEGER))]
        prompt_id: u64,
    },
    Stop {
        session_id: String,
    },
}
